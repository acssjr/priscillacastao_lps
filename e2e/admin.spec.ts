import { test, expect } from "@playwright/test";
import path from "node:path";
import { execFileSync } from "node:child_process";
import AxeBuilder from "@axe-core/playwright";
test("visual editing, inspector, three campaigns, publication, history, photos and users", async ({ page }) => {
  test.setTimeout(150000);
  const errors: string[] = []; page.on("pageerror",error => errors.push(error.message));
  await page.goto("/admin/ativar"); await expect(page).toHaveURL(/\/admin$/);
  await expect(page.getByLabel("Código de ativação")).toHaveCount(0);
  execFileSync(process.execPath,["scripts/create-admin.mjs"],{env:{...process.env,CMS_DATA_DIRECTORY:process.env.CMS_TEST_DIRECTORY,DATABASE_URL:"",ADMIN_INITIAL_PASSWORD:"test-password-123"}});
  await page.getByLabel("Usuário",{exact:true}).fill("admin"); await page.getByLabel("Senha",{exact:true}).fill("test-password-123");
  await page.getByRole("button",{name:"Entrar no painel",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Edição visual",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Edição avançada",exact:true})).toHaveCount(0);
  const frame = page.frameLocator('iframe[title="Site com edição visual"]');
  const inline = (field:string) => frame.locator(`[data-cms-field="${field}"]`);
  await expect(page.locator("[data-editor-ready=true]")).toBeVisible();
  await expect(inline("hero.title")).toBeVisible();
  const opening = await inline("hero.eyebrow").textContent();
  await inline("hero.eyebrow").press("End");
  await inline("hero.eyebrow").pressSequentially(" · ao seu ritmo",{delay:20});
  await expect(inline("hero.eyebrow")).toHaveText(opening + " · ao seu ritmo");
  await expect(page.locator('[class*="selection"]').getByLabel("Texto de abertura",{exact:true})).toHaveValue(opening + " · ao seu ritmo");
  // The real headline can be edited without repairing the emphasized phrase manually.
  await inline("hero.title").fill("Aprenda forró com a Priscilla no seu ritmo");
  await expect(page.locator('[class*="selection"]').getByLabel("Título",{exact:true})).toHaveValue("Aprenda forró com a Priscilla no seu ritmo");
  // Editing in the inspector updates the canvas, including empty intermediate drafts.
  await page.locator('[class*="selection"]').getByLabel("Título",{exact:true}).fill("Forró feito para você");
  await expect(inline("hero.title")).toHaveText("Forró feito para você");
  await page.getByRole("button",{name:"Desfazer",exact:true}).click();
  await expect(inline("hero.title")).toHaveText("Aprenda forró com a Priscilla no seu ritmo");
  await page.getByRole("button",{name:"Refazer",exact:true}).click();
  await expect(inline("hero.title")).toHaveText("Forró feito para você");
  await page.getByRole("button",{name:"Limpar seleção"}).click();
  expect((await new AxeBuilder({page}).include('[class*="shell"]').withTags(["wcag2a","wcag2aa"]).analyze()).violations).toEqual([]);
  await page.getByLabel("Parte do site").selectOption("faq");
  await inline("faq.title").fill("Dúvidas editadas pelo painel");
  await page.getByRole("button",{name:"Limpar seleção"}).click();
  await page.locator('details').filter({has:page.locator('summary').filter({hasText:/^Perguntas e respostas$/})}).locator('summary').click();
  await page.getByRole("button",{name:"Adicionar pergunta",exact:true}).click();
  await page.getByLabel("Pergunta",{exact:true}).last().fill("Posso remarcar minha aula?");
  await page.getByLabel("Resposta",{exact:true}).last().fill("Entre em contato para combinar uma nova data.");
  await expect(inline("faq.items.6.question")).toHaveText("Posso remarcar minha aula?");
  // Explore mode retains working disclosures, while external links stay inside the preview.
  await page.getByRole("button",{name:"Editar conteúdo",exact:true}).click();
  await frame.locator("#duvidas summary").last().click();
  await expect(frame.getByText("Entre em contato para combinar uma nova data.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Explorar prévia",exact:true}).click();
  await page.getByRole("button",{name:"Salvar rascunho",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"Rascunho salvo"})).toBeVisible();
  expect(await (await page.request.get("/")).text()).not.toContain("Dúvidas editadas pelo painel");
  for (const [id,title] of [["forro-evolucao","Dúvidas da evolução"],["forro-roots","Dúvidas do roots"]]) {
    await page.getByLabel("Página em edição").selectOption(id); await expect(inline("faq.title")).toBeAttached(); await inline("faq.title").fill(title);
    await expect(page.locator('[class*="selection"]').getByLabel("Título",{exact:true})).toHaveValue(title);
  }
  await page.getByRole("button",{name:"Publicar",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Confirmar publicação",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Publicar alterações",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Publicado no site local",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Voltar à edição",exact:true}).click();
  for (const [route,title] of [["/","Dúvidas editadas pelo painel"],["/evolua-no-forro","Dúvidas da evolução"],["/forro-roots","Dúvidas do roots"]]) expect(await (await page.request.get(route)).text()).toContain(title);
  await page.getByRole("button",{name:"Histórico de versões",exact:true}).click();
  await page.getByRole("button",{name:"Recuperar como rascunho",exact:true}).click(); await page.getByRole("button",{name:"Recuperar rascunho",exact:true}).click();
  await expect(page.getByRole("status").filter({hasText:"Versão recuperada"})).toBeVisible();
  expect(await (await page.request.get("/forro-roots")).text()).toContain("Dúvidas do roots");
  await page.getByRole("button",{name:"Editar no site",exact:true}).click(); await page.getByLabel("Parte do site").selectOption("hero");
  await expect(frame.getByRole("button",{name:"Alterar foto",exact:false}).first()).toBeVisible();
  await frame.getByRole("button",{name:"Alterar foto",exact:false}).first().click();
  await page.locator('input[type="file"]').setInputFiles(path.resolve("public/images/priscilla-castao-ensaio-01.webp"));
  await expect(page.getByRole("dialog",{name:"Escolher imagem"}).getByRole("status").filter({hasText:"Imagem adicionada"})).toBeVisible();
  await page.getByRole("button",{name:"Usar esta imagem",exact:true}).first().click();
  await page.locator('[class*="selection"]').getByLabel("Posição horizontal").fill("35");
  await expect(frame.locator('img[data-cms-image="hero.image"]')).toHaveCSS("object-position","35% 50%");
  // Focal-point control supports keyboard input and updates the actual photograph.
  await page.locator('[class*="selection"]').getByRole("slider",{name:"Enquadramento da imagem"}).press("ArrowRight");
  await expect(frame.locator('img[data-cms-image="hero.image"]')).toHaveCSS("object-position","37% 50%");
  await page.getByRole("button",{name:"Limpar seleção"}).click();
  await page.getByRole("button",{name:"Usuários",exact:true}).click(); await page.getByRole("button",{name:"Adicionar usuário",exact:true}).click();
  await page.getByLabel("Nome da pessoa").fill("Editora"); await page.getByLabel("Usuário de acesso").fill("editora");
  await page.getByLabel(/^Senha/).fill("editor-password"); await page.getByLabel("Repita a senha").fill("editor-password"); await page.getByRole("button",{name:"Criar acesso",exact:true}).click();
  await expect(page.getByText("@editora")).toBeVisible();
  await page.getByRole("button",{name:"Editar no site",exact:true}).click();
  await page.getByRole("combobox",{name:"Visualização",exact:true}).selectOption("mobile"); await expect(page.locator('iframe[title="Site com edição visual"]')).toHaveCSS("width","390px");
  await page.getByRole("combobox",{name:"Visualização",exact:true}).selectOption("desktop");
  await page.setViewportSize({width:390,height:844}); await page.getByRole("button",{name:"Menu",exact:true}).click();
  await page.getByRole("button",{name:"Visão geral",exact:true}).click(); expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect((await new AxeBuilder({page}).include('[class*="shell"]').withTags(["wcag2a","wcag2aa"]).analyze()).violations).toEqual([]);
  await page.goto("/#duvidas"); await expect(page.locator("[contenteditable=true]")).toHaveCount(0); await page.locator("#duvidas").evaluate(node => node.scrollIntoView({behavior:"instant"}));
  const titleLeft = await page.locator("#faq-title").evaluate(node => node.getBoundingClientRect().left), faqLeft = await page.locator("#duvidas summary").first().evaluate(node => node.getBoundingClientRect().left);
  expect(Math.abs(faqLeft-titleLeft)).toBeLessThan(2); expect(errors).toEqual([]);
});
